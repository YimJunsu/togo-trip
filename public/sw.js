/*
 * 설치를 위한 최소 서비스워커.
 *
 * 크롬은 fetch 핸들러가 있는 서비스워커가 등록돼 있어야 "앱 설치" 배너를 띄운다.
 * 그래서 핸들러는 두되, 아무것도 캐시하지 않고 네트워크로 그대로 넘긴다.
 *
 * 캐시를 하지 않는 것이 의도다. 이 서비스는 여행방·정산처럼 사람마다 다르고 자주
 * 바뀌는 데이터를 다루는데, 어설픈 캐시 규칙 하나가 "배포했는데 옛 화면이 남는" 사고로
 * 이어진다. 오프라인 지원이 필요해지면 그때 캐시할 대상을 정해서 따로 연다.
 *
 * 이 파일은 빌드 산출물이 아니라 손으로 관리한다. 경로가 /sw.js 라 스코프가 사이트
 * 전체(/)로 잡힌다 — 하위 경로에 두면 그 아래만 제어하게 되어 설치 조건을 못 채운다.
 */

self.addEventListener('install', () => {
  // 새 워커가 대기하지 않고 바로 활성화되게 한다. 캐시가 없으니 갈아타도 잃을 것이 없다.
  self.skipWaiting()
})

self.addEventListener('activate', (event) => {
  event.waitUntil(self.clients.claim())
})

self.addEventListener('fetch', () => {
  // 일부러 비워 둔다. respondWith를 부르지 않으면 브라우저가 평소대로 네트워크를 탄다.
  // 핸들러의 존재 자체가 설치 조건이다.
})
